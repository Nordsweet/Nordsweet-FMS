function compareRouteIds(left, right) {
  return String(left || "").localeCompare(String(right || ""), undefined, {
    numeric: true,
    sensitivity: "base"
  });
}

function getRouteFamilyId(pointId) {
  const normalizedPointId = normalizeThingId(pointId);
  const match = normalizedPointId.match(/^([A-Z]+)\d+[A-Z]?$/);
  return match ? match[1] : "";
}

function getRouteFamilyMembers(airportData, familyId) {
  const normalizedFamilyId = normalizeThingId(familyId);
  if (!normalizedFamilyId || !airportData || !Array.isArray(airportData.elements)) {
    return [];
  }

  const familyPattern = new RegExp("^" + normalizedFamilyId.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\\d+[A-Z]?$");
  return airportData.elements
    .filter((thing) => thing.type === "taxiway" && familyPattern.test(thing.id))
    .map((thing) => thing.id)
    .sort(compareRouteIds);
}

function isRouteFamilyAlias(airportData, optionId) {
  return getRouteFamilyMembers(airportData, optionId).length > 1;
}

function getRouteFamilyEntryPoint(airportData, standId, familyId, previousPoint) {
  const familyMembers = getRouteFamilyMembers(airportData, familyId);
  const normalizedPreviousPoint = normalizeThingId(previousPoint);
  if (normalizedPreviousPoint && airportData.connections && airportData.connections[normalizedPreviousPoint]) {
    const connectedEntry = familyMembers
      .filter((memberId) => airportData.connections[normalizedPreviousPoint].includes(memberId))
      .sort(compareRouteIds)[0];
    if (connectedEntry) {
      return connectedEntry;
    }
  }

  const normalizedStandId = normalizeThingId(standId);
  const standEntry = normalizedStandId && airportData.connections && airportData.connections[normalizedStandId]
    ? airportData.connections[normalizedStandId]
        .map(normalizeThingId)
        .filter((optionId) => familyMembers.includes(optionId))
        .sort(compareRouteIds)[0]
    : "";
  return standEntry || familyMembers[0] || normalizeThingId(familyId);
}

function findRoutePath(airportData, startId, targetId, allowedIds) {
  const normalizedStartId = normalizeThingId(startId);
  const normalizedTargetId = normalizeThingId(targetId);
  const allowed = new Set((Array.isArray(allowedIds) ? allowedIds : []).map(normalizeThingId));
  const queue = [{ point: normalizedStartId, path: [normalizedStartId] }];
  const visited = new Set([normalizedStartId]);

  while (queue.length) {
    const current = queue.shift();
    const neighbors = airportData.connections && airportData.connections[current.point]
      ? airportData.connections[current.point].map(normalizeThingId).sort(compareRouteIds)
      : [];

    for (const neighbor of neighbors) {
      if (neighbor === normalizedTargetId) {
        return current.path.concat(neighbor);
      }
      if (!allowed.has(neighbor) || visited.has(neighbor)) {
        continue;
      }
      visited.add(neighbor);
      queue.push({ point: neighbor, path: current.path.concat(neighbor) });
    }
  }

  return [];
}

function getRouteFutureChoiceScore(airportData, candidateId, followingChoice) {
  const normalizedCandidateId = normalizeThingId(candidateId);
  const normalizedFollowingChoice = normalizeThingId(followingChoice);
  if (!normalizedCandidateId || !normalizedFollowingChoice) {
    return 0;
  }

  const candidateConnections = airportData.connections && airportData.connections[normalizedCandidateId]
    ? airportData.connections[normalizedCandidateId].map(normalizeThingId)
    : [];
  if (candidateConnections.includes(normalizedFollowingChoice)) {
    return -100;
  }

  if (isRouteFamilyAlias(airportData, normalizedFollowingChoice)) {
    const followingMembers = getRouteFamilyMembers(airportData, normalizedFollowingChoice);
    if (candidateConnections.some((connectionId) => followingMembers.includes(connectionId))) {
      return -90;
    }
  }

  return 0;
}

function getRouteFamilyExitRoute(airportData, familyId, currentPoint, nextChoice, followingChoice) {
  const familyMembers = getRouteFamilyMembers(airportData, familyId);
  const currentFamilyId = getRouteFamilyId(currentPoint);
  if (!familyMembers.length || currentFamilyId !== normalizeThingId(familyId)) {
    return [];
  }

  const targetCandidates = isRouteFamilyAlias(airportData, nextChoice)
    ? getRouteFamilyMembers(airportData, nextChoice)
    : [normalizeThingId(nextChoice)];
  const bestPath = targetCandidates
    .map((targetId) => findRoutePath(airportData, currentPoint, targetId, familyMembers))
    .filter((path) => path.length > 1)
    .sort((left, right) => {
      const leftFutureScore = getRouteFutureChoiceScore(airportData, left[left.length - 1], followingChoice);
      const rightFutureScore = getRouteFutureChoiceScore(airportData, right[right.length - 1], followingChoice);
      if (leftFutureScore !== rightFutureScore) {
        return leftFutureScore - rightFutureScore;
      }
      if (left.length !== right.length) {
        return left.length - right.length;
      }
      return compareRouteIds(left[left.length - 1], right[right.length - 1]);
    })[0] || [];
  return bestPath.length > 1 ? bestPath.slice(1) : [];
}

function getRouteExpansion(airportData, previousChoice, nextChoice) {
  const expansionKey = String(previousChoice || "START").toUpperCase() + ">" + String(nextChoice || "").toUpperCase();
  const expansion = airportData && airportData.expansions ? airportData.expansions[expansionKey] : null;
  if (!expansion) {
    return {
      replacePrevious: false,
      route: nextChoice ? [nextChoice] : []
    };
  }

  if (Array.isArray(expansion)) {
    return {
      replacePrevious: false,
      route: expansion.slice()
    };
  }

  return {
    replacePrevious: Boolean(expansion.replacePrevious),
    route: Array.isArray(expansion.route) ? expansion.route.slice() : []
  };
}

function appendExpandedRoutePoint(expandedRoute, point) {
  const normalizedPoint = normalizeThingId(point);
  if (!normalizedPoint) {
    return;
  }

  if (expandedRoute[expandedRoute.length - 1] !== normalizedPoint) {
    expandedRoute.push(normalizedPoint);
  }

  const runwayEndpoint = getRunwayEndpointFromHoldingPoint(normalizedPoint);
  if (runwayEndpoint && expandedRoute[expandedRoute.length - 1] !== runwayEndpoint) {
    expandedRoute.push(runwayEndpoint);
  }
}

function maybeAppendImplicitBacktrackPoint(airportData, expandedRoute, normalizedChoice, previousChoice) {
  const currentPoint = normalizeThingId(normalizedChoice);
  const previousPoint = normalizeThingId(previousChoice);
  if (!isRunwayEndpoint(currentPoint)) {
    return;
  }

  if (isRunwayEndpoint(previousPoint) || expandedRoute.includes(currentPoint)) {
    return;
  }

  const previousHoldingRunwayEndpoint = getRunwayEndpointFromHoldingPoint(previousPoint);
  const oppositeRunwayEndpoint = getOppositeRunwayEndpoint(currentPoint);
  if (
    previousHoldingRunwayEndpoint &&
    oppositeRunwayEndpoint &&
    previousHoldingRunwayEndpoint === oppositeRunwayEndpoint &&
    getThingById(airportData, oppositeRunwayEndpoint)
  ) {
    appendExpandedRoutePoint(expandedRoute, oppositeRunwayEndpoint);
  }
}

function parseRoutePreviewText(text, airportData) {
  const ignoredWords = new Set(["STAND", "VIA", "TO", "FROM", "TAXI", "ROUTE", "HOLDING", "POINT", "APRON"]);
  const normalizedText = String(text || "")
    .toUpperCase()
    .replace(/\bRUNWAY\s*([0-9]{2}[A-Z]?)\b/g, " RW$1 ")
    .replace(/\bRWY\s*([0-9]{2}[A-Z]?)\b/g, " RW$1 ")
    .replace(/\bHP\s*([0-9]{2}[A-Z]?)\b/g, " HP$1 ");
    const rawTokens = normalizedText.match(/[A-Z]+\d+[A-Z]?|\d+[A-Z]?(?:\/[A-Z0-9]+)?|[A-Z]+/g) || [];
  return rawTokens
    .map(normalizeThingId)
    .filter((token) => token && !ignoredWords.has(token))
    .filter((token) => getThingById(airportData, token) || isRouteFamilyAlias(airportData, token));
}

function expandRoutePreviewTokens(airportData, routeTokens) {
  const tokens = (Array.isArray(routeTokens) ? routeTokens : []).map(normalizeThingId).filter(Boolean);
  const firstThing = tokens.length ? getThingById(airportData, tokens[0]) : null;
  const standId = firstThing && firstThing.type === "stand" ? tokens[0] : "";
  const choices = standId ? tokens.slice(1) : tokens.slice();
  const expandedRoute = [];
  let previousChoice = "";

  choices.forEach((normalizedChoice, choiceIndex) => {
    const followingChoice = choices[choiceIndex + 1] || "";

    if (isRouteFamilyAlias(airportData, previousChoice)) {
      const familyRoute = getRouteFamilyExitRoute(
        airportData,
        previousChoice,
        expandedRoute[expandedRoute.length - 1],
        normalizedChoice,
        followingChoice
      );
      if (familyRoute.length) {
        familyRoute.forEach((point) => appendExpandedRoutePoint(expandedRoute, point));
        previousChoice = normalizedChoice;
        return;
      }
    }

    if (isRouteFamilyAlias(airportData, normalizedChoice)) {
      maybeAppendImplicitBacktrackPoint(airportData, expandedRoute, normalizedChoice, previousChoice);
      appendExpandedRoutePoint(
        expandedRoute,
        getRouteFamilyEntryPoint(airportData, standId, normalizedChoice, expandedRoute[expandedRoute.length - 1])
      );
      previousChoice = normalizedChoice;
      return;
    }

    const expansion = getRouteExpansion(airportData, previousChoice, normalizedChoice);
    if (expansion.replacePrevious && expandedRoute.length) {
      expandedRoute.pop();
    }

    maybeAppendImplicitBacktrackPoint(airportData, expandedRoute, normalizedChoice, previousChoice);
    expansion.route.forEach((point) => appendExpandedRoutePoint(expandedRoute, point));
    previousChoice = normalizedChoice;
  });

  return expandedRoute;
}

function getDistanceBetweenPoints(left, right) {
  if (!left || !right) {
    return 0;
  }
  const deltaX = toNumber(left.x, 0) - toNumber(right.x, 0);
  const deltaY = toNumber(left.y, 0) - toNumber(right.y, 0);
  return Math.sqrt(deltaX * deltaX + deltaY * deltaY);
}

