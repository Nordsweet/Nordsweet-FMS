function getIntersectionSemanticInfo(airportData, intersection) {
  const typedMembers = getTypedIntersectionMembers(airportData, intersection);
  const standMembers = typedMembers.filter((member) => member.type === "stand").map((member) => member.id);
  const taxiwayMembers = typedMembers.filter((member) => member.type === "taxiway").map((member) => member.id);
  const arpMembers = typedMembers.filter((member) => member.type === "arp").map((member) => member.id);
  const vorMembers = typedMembers.filter((member) => member.type === "vor").map((member) => member.id);

  if (typedMembers.length === 1 && standMembers.length === 1) {
    return {
      kind: "stand-location",
      text: "Stand location: " + standMembers[0]
    };
  }

  if (typedMembers.length === 1 && arpMembers.length === 1) {
    return {
      kind: "arp-location",
      text: "ARP location"
    };
  }

  if (typedMembers.length === 1 && vorMembers.length === 1) {
    return {
      kind: "vor-location",
      text: "VOR location: " + vorMembers[0]
    };
  }

  if (standMembers.length && taxiwayMembers.length) {
    return {
      kind: "stand-exit",
      text: "Stand exit: " + standMembers.join(", ") + " via " + taxiwayMembers.join(", ")
    };
  }

  if (typedMembers.length === 1 && taxiwayMembers.length === 1) {
    return {
      kind: "centerline-point",
      text: "Taxiway centerline shaping point: " + taxiwayMembers[0]
    };
  }

  if (typedMembers.length >= 2) {
    return {
      kind: "routing-intersection",
      text: "Routing intersection: " + typedMembers.map((member) => member.id).join(", ")
    };
  }

  return {
    kind: "empty",
    text: "No members yet. Select stand/taxiway/holding point members."
  };
}

