function getTaxiwayPathValidation(airportData, taxiwayId) {
  const taxiway = normalizeThingId(taxiwayId);
  const thing = getThingById(airportData, taxiway);
  if (!taxiway || !thing || thing.type !== "taxiway") {
    return {
      hasIssue: false,
      text: ""
    };
  }

  const pathPoints = getTaxiwayPathPoints(airportData, taxiway);
  const pathIntersectionIds = getUniqueIntersectionIds(pathPoints.map((point) => getIntersectionIdForPathPoint(airportData, point)));
  const memberIntersectionIds = getUniqueIntersectionIds(getIntersectionsForMember(airportData, taxiway).map((intersection) => intersection.id));
  const pathIntersectionSet = new Set(pathIntersectionIds);
  const memberIntersectionSet = new Set(memberIntersectionIds);
  const pathOnly = pathIntersectionIds.filter((intersectionId) => !memberIntersectionSet.has(intersectionId));
  const memberOnly = memberIntersectionIds.filter((intersectionId) => !pathIntersectionSet.has(intersectionId));
  const rawPathPointCount = Math.max(0, pathPoints.length - pathIntersectionIds.length);
  const countMismatch = pathPoints.length !== memberIntersectionIds.length;
  const hasIssue = countMismatch || pathOnly.length > 0 || memberOnly.length > 0;
  if (!hasIssue) {
    return {
      hasIssue: false,
      text: taxiway + " path validation OK."
    };
  }

  const details = [
    taxiway + " has " + pathPoints.length + " path point" + (pathPoints.length === 1 ? "" : "s") + " and " + memberIntersectionIds.length + " intersection" + (memberIntersectionIds.length === 1 ? "" : "s") + " containing " + taxiway + ". Is this intentional?",
    "Path-linked intersections: " + pathIntersectionIds.length + (rawPathPointCount ? " + " + rawPathPointCount + " raw chart point" + (rawPathPointCount === 1 ? "" : "s") : "") + ".",
    memberOnly.length ? "Extra intersections containing " + taxiway + ": " + memberOnly.join(", ") + "." : "",
    pathOnly.length ? "Path points not marked with " + taxiway + ": " + pathOnly.join(", ") + "." : ""
  ].filter(Boolean);

  return {
    hasIssue: true,
    text: details.join(" ")
  };
}

