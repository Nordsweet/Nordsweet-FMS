function parseCompactDmsCoordinate(raw, axis, sign) {
  const compact = clean(raw).toUpperCase().replace(/[NSEW+-]/g, "").replace(/\D/g, "");
  const degreeWidth = axis === "lat" ? 2 : 3;
  if (compact.length < degreeWidth + 2) {
    return null;
  }

  const degrees = Number(compact.slice(0, degreeWidth));
  const minutes = Number(compact.slice(degreeWidth, degreeWidth + 2));
  const secondsText = compact.slice(degreeWidth + 2);
  const seconds = secondsText ? Number(secondsText) : 0;
  if (![degrees, minutes, seconds].every(Number.isFinite) || minutes >= 60 || seconds >= 60) {
    return null;
  }
  return sign * (degrees + minutes / 60 + seconds / 3600);
}

function parseCoordinateValue(value, axis) {
  const raw = clean(value).toUpperCase().replace(/,/g, ".");
  if (!raw) {
    return 0;
  }

  const decimal = Number(raw);
  if (Number.isFinite(decimal)) {
    return clamp(decimal, axis === "lat" ? -90 : -180, axis === "lat" ? 90 : 180);
  }

  const hemisphereMatch = raw.match(/[NSEW]/);
  const hemisphere = hemisphereMatch ? hemisphereMatch[0] : "";
  const sign = /[SW]/.test(hemisphere) || /^\s*-/.test(raw) ? -1 : 1;
  const parts = (raw
    .replace(/[NSEW]/g, " ")
    .replace(/[^\d.+-]+/g, " ")
    .trim()
    .match(/[+-]?\d+(?:\.\d+)?/g) || [])
    .map(Number)
    .filter(Number.isFinite);

  if (!parts.length) {
    return 0;
  }

  const compactCoordinate = parts.length === 1 && /[NSEW]/.test(raw)
    ? parseCompactDmsCoordinate(raw, axis, sign)
    : null;
  if (Number.isFinite(compactCoordinate)) {
    return clamp(compactCoordinate, axis === "lat" ? -90 : -180, axis === "lat" ? 90 : 180);
  }

  const degrees = Math.abs(parts[0]);
  const minutes = Math.abs(parts[1] || 0);
  const seconds = Math.abs(parts[2] || 0);
  const coordinate = sign * (degrees + minutes / 60 + seconds / 3600);
  return clamp(coordinate, axis === "lat" ? -90 : -180, axis === "lat" ? 90 : 180);
}

function parseCoordinatePair(value) {
  const raw = clean(value).toUpperCase();
  const numberTokens = raw.match(/[+-]?\d+(?:[\.,]\d+)?/g) || [];
  if (!/[NSEW]/.test(raw)) {
    if (numberTokens.length === 2) {
      return {
        lat: parseCoordinateValue(numberTokens[0], "lat"),
        lon: parseCoordinateValue(numberTokens[1], "lon")
      };
    }
    if (numberTokens.length >= 6) {
      return {
        lat: parseCoordinateValue(numberTokens.slice(0, 3).join(" "), "lat"),
        lon: parseCoordinateValue(numberTokens.slice(3, 6).join(" "), "lon")
      };
    }
  }

  const latEnd = Math.max(raw.indexOf("N"), raw.indexOf("S"));
  const lonEnd = Math.max(raw.indexOf("E"), raw.indexOf("W"));
  if (latEnd < 0 || lonEnd < 0) {
    return null;
  }

  if (latEnd === 0 && lonEnd > 0) {
    return {
      lat: parseCoordinateValue(raw.slice(0, lonEnd), "lat"),
      lon: parseCoordinateValue(raw.slice(lonEnd), "lon")
    };
  }

  if (lonEnd === 0 && latEnd > 0) {
    return {
      lat: parseCoordinateValue(raw.slice(latEnd), "lat"),
      lon: parseCoordinateValue(raw.slice(0, latEnd), "lon")
    };
  }

  if (latEnd < lonEnd) {
    return {
      lat: parseCoordinateValue(raw.slice(0, latEnd + 1), "lat"),
      lon: parseCoordinateValue(raw.slice(latEnd + 1, lonEnd + 1), "lon")
    };
  }

  return {
    lat: parseCoordinateValue(raw.slice(lonEnd + 1, latEnd + 1), "lat"),
    lon: parseCoordinateValue(raw.slice(0, lonEnd + 1), "lon")
  };
}

