function getChartPointFromEvent(event) {
  const rect = refs.chartOverlaySvg.getBoundingClientRect();
  if (!rect.width || !rect.height) {
    return { x: 0, y: 0 };
  }
  return {
    x: toOverlayCoordinate(((event.clientX - rect.left) / rect.width) * 1000),
    y: toOverlayCoordinate(((event.clientY - rect.top) / rect.height) * 1000)
  };
}

function getUniqueIntersectionId(airportData, point) {
  const overlay = getChartOverlayData(airportData);
  const takenIds = new Set(overlay.intersections.map((intersection) => intersection.id));
  const baseId = normalizeIntersectionId("INT-" + Math.round(point.x) + "-" + Math.round(point.y));
  if (!takenIds.has(baseId)) {
    return baseId;
  }
  let index = 2;
  while (takenIds.has(baseId + "-" + index)) {
    index += 1;
  }
  return baseId + "-" + index;
}

