function inferThingType(id) {
  const normalized = normalizeThingId(id);
  if (normalized === "ARP") {
    return "arp";
  }
  if (/^HP\d+/i.test(normalized)) {
    return "holdingPoint";
  }
  if (/^RW\d+[A-Z]?$/i.test(normalized)) {
    return "runway";
  }
  if (/^\d+[A-Z]?(?:\/[A-Z0-9]+)?$/i.test(normalized)) {
    return "stand";
  }
  return "taxiway";
}

function normalizeThingType(type, id) {
  const cleanedType = clean(type);
  const inferredType = inferThingType(id);
  if (inferredType === "stand" && cleanedType === "taxiway") {
    return "stand";
  }
  return cleanedType || inferredType;
}

