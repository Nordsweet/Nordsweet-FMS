function formatCoordinateDms(value, axis) {
  const coordinate = Number(value);
  if (!Number.isFinite(coordinate) || coordinate === 0) {
    return "";
  }

  const hemisphere = axis === "lat"
    ? (coordinate < 0 ? "S" : "N")
    : (coordinate < 0 ? "W" : "E");
  let remainingSeconds = Math.round(Math.abs(coordinate) * 3600);
  let degrees = Math.floor(remainingSeconds / 3600);
  remainingSeconds -= degrees * 3600;
  let minutes = Math.floor(remainingSeconds / 60);
  let seconds = remainingSeconds - minutes * 60;
  if (seconds >= 60) {
    seconds -= 60;
    minutes += 1;
  }
  if (minutes >= 60) {
    minutes -= 60;
    degrees += 1;
  }

  const degreeWidth = axis === "lat" ? 2 : 3;
  const degreeSymbol = String.fromCharCode(176);
  return String(degrees).padStart(degreeWidth, "0") +
    degreeSymbol +
    String(minutes).padStart(2, "0") +
    "'" +
    String(seconds).padStart(2, "0") +
    '" ' +
    hemisphere;
}

