function normalizeRunwayId(value) {
  return clean(value).replace(/\s+/g, "").toUpperCase();
}

function normalizeSurface(value) {
  const surface = clean(value).toLowerCase();
  if (surface === "concrete") {
    return "concrete";
  }
  if (surface === "grass") {
    return "grass";
  }
  if (surface === "asphalt" || surface === "paved") {
    return "paved";
  }
  return surface || "paved";
}

function normalizeRunwayHeading(value, fallback = 0) {
  const heading = toNumber(value, fallback);
  if (!Number.isFinite(Number(heading))) {
    return 0;
  }
  return ((Math.round(heading) % 360) + 360) % 360;
}

function normalizeAirportRunway(rawRunway) {
  const id = normalizeRunwayId(rawRunway && rawRunway.id);
  const fallbackHeading = getRunwayHeadingFromId(id);
  const magHdg = normalizeRunwayHeading(
    rawRunway && (rawRunway.magHdg ?? rawRunway.magneticHdg ?? rawRunway.hdg),
    fallbackHeading
  );
  const trueHdg = normalizeRunwayHeading(
    rawRunway && (rawRunway.trueHdg ?? rawRunway.geographicHdg ?? rawRunway.geoHdg),
    magHdg
  );
  const tora = Math.max(0, Math.round(toNumber(rawRunway && rawRunway.tora, toNumber(rawRunway && rawRunway.length_m, 0))));
  const toda = Math.max(0, Math.round(toNumber(rawRunway && rawRunway.toda, tora)));
  const asda = Math.max(0, Math.round(toNumber(rawRunway && rawRunway.asda, tora)));
  const lda = Math.max(0, Math.round(toNumber(rawRunway && rawRunway.lda, tora)));
  const lengthM = Math.max(
    Math.max(0, Math.round(toNumber(rawRunway && rawRunway.length_m, 0))),
    tora,
    toda,
    asda,
    lda
  );
  const thresholdCandidate = rawRunway && (rawRunway.threshold || rawRunway.thresholdCoordinates);
  const rawThreshold = thresholdCandidate && typeof thresholdCandidate === "object" && !Array.isArray(thresholdCandidate)
    ? thresholdCandidate
    : {};
  const thresholdLat = Object.prototype.hasOwnProperty.call(rawThreshold, "lat")
    ? rawThreshold.lat
    : rawRunway && (rawRunway.thresholdLat ?? rawRunway.thrLat ?? rawRunway.lat);
  const thresholdLon = Object.prototype.hasOwnProperty.call(rawThreshold, "lon")
    ? rawThreshold.lon
    : rawRunway && (rawRunway.thresholdLon ?? rawRunway.thrLon ?? rawRunway.lon);
  const threshold = normalizeRunwayThresholdData(rawThreshold, id, thresholdLat, thresholdLon);
  return {
    id,
    hdg: magHdg,
    trueHdg,
    magHdg,
    threshold,
    surface: normalizeSurface(rawRunway && rawRunway.surface),
    slope: Math.round(toNumber(rawRunway && rawRunway.slope, 0) * 10) / 10,
    length_m: lengthM,
    width_m: Math.max(0, Math.round(toNumber(rawRunway && rawRunway.width_m, 30))),
    tora,
    toda,
    asda,
    lda
  };
}

function normalizeAirportArpData(rawArp = {}, fallbackLat = 0, fallbackLon = 0) {
  return {
    id: "ARP",
    lat: roundCoordinate(parseCoordinateValue(
      Object.prototype.hasOwnProperty.call(rawArp, "lat") ? rawArp.lat : fallbackLat,
      "lat"
    )),
    lon: roundCoordinate(parseCoordinateValue(
      Object.prototype.hasOwnProperty.call(rawArp, "lon") ? rawArp.lon : fallbackLon,
      "lon"
    ))
  };
}

function getOppositeRunwayId(runwayId) {
  const match = normalizeRunwayId(runwayId).match(/^(\d{1,2})([LRC]?)$/);
  if (!match) {
    return "";
  }

  const runwayNumber = Math.max(1, Math.min(toNumber(match[1], 36), 36));
  const oppositeNumber = ((runwayNumber + 17) % 36) + 1;
  const oppositeSuffix = match[2] === "L" ? "R" : match[2] === "R" ? "L" : match[2];
  return String(oppositeNumber).padStart(2, "0") + oppositeSuffix;
}

function getRunwayHeadingFromId(runwayId) {
  const match = normalizeRunwayId(runwayId).match(/^(\d{1,2})/);
  if (!match) {
    return 0;
  }

  const runwayNumber = Math.max(1, Math.min(toNumber(match[1], 36), 36));
  return runwayNumber === 36 ? 360 : runwayNumber * 10;
}

function getNextRunwaySuggestion(runways) {
  const usedIds = new Set((Array.isArray(runways) ? runways : []).map((runway) => normalizeRunwayId(runway && runway.id)).filter(Boolean));
  const lastRunway = Array.isArray(runways) && runways.length ? runways[runways.length - 1] : null;
  const oppositeId = getOppositeRunwayId(lastRunway && lastRunway.id);
  if (oppositeId && !usedIds.has(oppositeId)) {
    return oppositeId;
  }

  const commonPairs = ["25", "07", "28", "10", "27", "09", "36", "18", "29", "11", "30", "12", "31", "13", "32", "14", "33", "15", "34", "16", "35", "17"];
  const commonCandidate = commonPairs.find((candidate) => !usedIds.has(candidate));
  if (commonCandidate) {
    return commonCandidate;
  }

  for (let runwayNumber = 1; runwayNumber <= 36; runwayNumber += 1) {
    const candidate = String(runwayNumber).padStart(2, "0");
    if (!usedIds.has(candidate)) {
      return candidate;
    }
  }

  return "";
}

