function getOppositeRunwayEndpoint(runwayEndpointId) {
  const match = normalizeThingId(runwayEndpointId).match(/^RW(\d{1,2})([LRC]?)$/);
  if (!match) {
    return "";
  }

  const runwayNumber = Math.max(1, Math.min(toNumber(match[1], 36), 36));
  const oppositeNumber = ((runwayNumber + 17) % 36) + 1;
  const oppositeSuffix = match[2] === "L" ? "R" : match[2] === "R" ? "L" : match[2];
  return "RW" + String(oppositeNumber).padStart(2, "0") + oppositeSuffix;
}

