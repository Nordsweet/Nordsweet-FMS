function getApronGroupCode(apron) {
  const apronId = normalizeThingId(apron && apron.id);
  const apronLabel = clean(apron && apron.label).toUpperCase();
  if (apronId === "CIVILIAN" || /^CIVILIAN\s*APRON$/.test(apronLabel)) {
    return "";
  }
  if (apronId === "MILITARY" || /^MILITARY\s*APRON$/.test(apronLabel)) {
    return "M";
  }
  if (apronId === "MAIN" || /^MAIN\s*APRON$/.test(apronLabel)) {
    return "MA";
  }

  const source = (apronLabel + " " + apronId).trim();
  const apronMatch = source.match(/\bAPRON\s*([0-9A-Z]+)\b/) || apronId.match(/^APRON([0-9A-Z]+)$/);
  if (apronMatch) {
    return "A" + apronMatch[1];
  }
  if (/^A[0-9A-Z]+$/.test(apronId)) {
    return apronId;
  }

  const initials = (apronLabel || apronId)
    .split(/[^A-Z0-9]+/)
    .filter(Boolean)
    .map((word) => word[0])
    .join("");
  return initials || apronId || "AP";
}

function normalizeApronGroupCode(value) {
  const normalized = normalizeThingId(value);
  if (normalized === "CIVILIAN" || normalized === "ACIVILIAN" || normalized === "C") {
    return "";
  }
  if (normalized === "MILITARY" || normalized === "AMILITARY") {
    return "M";
  }
  if (normalized === "MAIN" || normalized === "MAINAPRON") {
    return "MA";
  }
  const apronMatch = normalized.match(/^APRON([0-9A-Z]+)$/);
  if (apronMatch) {
    return "A" + apronMatch[1];
  }
  return normalized;
}

