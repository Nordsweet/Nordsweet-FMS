function toggleIntersectionMember(memberId) {
  const airportData = getAirportData(selectedAirport, true);
  const selected = getSelectedIntersection(airportData);
  if (!selected) {
    setStatus("Choose or add an intersection first.", "warn");
    return;
  }

  const normalizedMemberId = normalizeThingId(memberId);
  if (!getThingById(airportData, normalizedMemberId)) {
    setStatus(normalizedMemberId + " does not exist at " + selectedAirport + ".", "warn");
    return;
  }

  const members = new Set(selected.members || []);
  if (members.has(normalizedMemberId)) {
    members.delete(normalizedMemberId);
  } else {
    members.add(normalizedMemberId);
  }

  selected.members = sortConnectionIds(Array.from(members));
  const semantic = getIntersectionSemanticInfo(airportData, selected);
  const memberThing = getThingById(airportData, normalizedMemberId);
  if (memberThing && memberThing.type === "taxiway") {
    setTaxiwayPathAwareStatus(
      airportData,
      normalizedMemberId,
      "Intersection " + selected.id + ": " + semantic.text + ".",
      selected.members.length ? "ok" : "warn"
    );
  } else {
    setStatus(
      "Intersection " + selected.id + ": " + semantic.text + ".",
      selected.members.length ? "ok" : "warn"
    );
  }
  render();
}

function renameThingId(airportData, oldId, newId) {
  const previousId = normalizeThingId(oldId);
  const nextId = normalizeThingId(newId);
  if (!airportData || !previousId || !nextId || previousId === nextId) {
    return previousId;
  }
  if (getThingById(airportData, nextId)) {
    setStatus(nextId + " already exists at " + selectedAirport + ".", "warn");
    return previousId;
  }

  const thing = getThingById(airportData, previousId);
  if (thing) {
    thing.id = nextId;
  }
  const previousConnections = airportData.connections[previousId] || [];
  airportData.connections[nextId] = sortConnectionIds((airportData.connections[nextId] || []).concat(previousConnections));
  delete airportData.connections[previousId];
  Object.keys(airportData.connections || {}).forEach((fromId) => {
    airportData.connections[fromId] = sortConnectionIds((airportData.connections[fromId] || []).map((targetId) => (
      normalizeThingId(targetId) === previousId ? nextId : targetId
    )));
  });
  (Array.isArray(airportData.chartOverlay && airportData.chartOverlay.intersections) ? airportData.chartOverlay.intersections : []).forEach((intersection) => {
    if (intersection && Array.isArray(intersection.members)) {
      intersection.members = sortConnectionIds(intersection.members.map((memberId) => (
        normalizeThingId(memberId) === previousId ? nextId : memberId
      )));
    }
  });
  return nextId;
}

function updateSelectedThing() {
  const airportData = getAirportData(selectedAirport, true);
  const selected = getThingById(airportData, selectedThing);
  if (!selected) {
    setStatus("Choose a thing to update first.", "warn");
    return;
  }

  let nextId = selected.id;
  if (selected.type === "vor") {
    const nextCode = normalizeVorCode(refs.thingVorCodeInput.value || selected.code || selected.id);
    if (!nextCode) {
      setStatus("VOR needs a 3-letter code.", "warn");
      return;
    }
    nextId = renameThingId(airportData, selected.id, nextCode);
    if (nextId !== nextCode) {
      render();
      return;
    }
    selectedThing = nextId;
    const updatedVor = getThingById(airportData, nextId);
    if (updatedVor) {
      updatedVor.code = nextCode;
      updatedVor.frequency = normalizeVorFrequency(refs.thingVorFrequencyInput.value);
      updatedVor.label = clean(refs.thingLabelInput.value) || ["VOR", nextCode, updatedVor.frequency].filter(Boolean).join(" ");
    }
  } else {
    selected.label = clean(refs.thingLabelInput.value) || getSuggestedThingLabel(selected.type, selected.id) || selected.id;
  }

  ensureBidirectionalConnections(airportData);
  refs.exportText.value = generateFileText();
  setStatus("Updated " + selectedThing + ".", "ok");
  render();
}

function addThing() {
  const selectedType = clean(refs.typeSelect.value);
  const vorCode = normalizeVorCode(refs.newThingVorCodeInput.value || refs.newThingInput.value);
  const rawThingId = selectedType === "vor"
    ? vorCode
    : normalizeThingId(refs.newThingInput.value);
  const airportData = getAirportData(selectedAirport, true);
  if (!rawThingId) {
    setStatus(selectedType === "vor" ? "Enter 3-letter VOR code first." : "Enter item id first, e.g. F, HP07 or B1.", "warn");
    return;
  }
  const thingType = normalizeThingType(selectedType, rawThingId);
  const selectedStandApron = thingType === "stand" ? getSelectedStandApron(airportData) : null;
  const thingId = thingType === "stand"
    ? (selectedStandApron ? getApronScopedStandId(rawThingId, selectedStandApron) : rawThingId)
    : rawThingId;
  if (airportData.elements.some((thing) => thing.id === thingId)) {
    setStatus(thingId + " already exists at " + selectedAirport + ".", "warn");
    return;
  }
  syncSuggestedThingLabel();
  const vorFrequency = thingType === "vor" ? normalizeVorFrequency(refs.newThingVorFrequencyInput.value) : "";
  const thingLabel = clean(refs.newThingLabelInput.value) || (thingType === "vor"
    ? ["VOR", vorCode || thingId, vorFrequency].filter(Boolean).join(" ")
    : getSuggestedThingLabel(thingType, thingId) || thingId);
  const nextThing = {
    id: thingId,
    type: thingType,
    label: thingLabel
  };
  if (thingType === "vor") {
    nextThing.code = vorCode || thingId;
    nextThing.frequency = vorFrequency;
  }
  airportData.elements.push(nextThing);
  airportData.connections[thingId] = [];
  if (thingType === "stand" && selectedStandApron) {
    ensureStandInApron(airportData, thingId, thingLabel, selectedStandApron);
  }
  if (thingType === "apron") {
    ensureApronGroup(airportData, thingId, thingLabel);
    selectedNewThingGroup = thingId;
  }
  selectedThing = thingId;
  refs.newThingInput.value = "";
  refs.newThingLabelInput.value = "";
  refs.newThingVorCodeInput.value = "";
  refs.newThingVorFrequencyInput.value = "";
  lastSuggestedThingLabel = "";
  setStatus("Added " + thingId + " to " + selectedAirport + ".", "ok");
  render();
}

function toggleConnection(targetId) {
  const airportData = getAirportData(selectedAirport, true);
  if (!selectedThing || !targetId || selectedThing === targetId) {
    return;
  }
  if (!canConnectThingIds(airportData, selectedThing, targetId)) {
    setStatus("Stand can connect only with taxiways.", "warn");
    return;
  }
  const sourceConnections = new Set(airportData.connections[selectedThing] || []);
  const targetConnections = new Set(airportData.connections[targetId] || []);
  if (sourceConnections.has(targetId)) {
    sourceConnections.delete(targetId);
    targetConnections.delete(selectedThing);
    setStatus("Disconnected " + selectedThing + " from " + targetId + ".", "ok");
  } else {
    sourceConnections.add(targetId);
    targetConnections.add(selectedThing);
    setStatus("Connected " + selectedThing + " with " + targetId + ".", "ok");
  }
  airportData.connections[selectedThing] = sortConnectionIds(Array.from(sourceConnections));
  airportData.connections[targetId] = sortConnectionIds(Array.from(targetConnections));
  ensureBidirectionalConnections(airportData);
  syncStandStartOptions(airportData);
  render();
}

function parseGroundDataFile(text) {
  const sandbox = {};
  const fakeWindow = sandbox;
  new Function("window", text + "\nreturn window.NORDSWEET_GROUND_DATA;")(fakeWindow);
  return fakeWindow.NORDSWEET_GROUND_DATA || { airports: {} };
}

async function openGroundDataFile() {
  if (!window.showOpenFilePicker) {
    setStatus("Your browser cannot open files directly here. Use the generated textarea/download instead.", "warn");
    return;
  }
  try {
    const [handle] = await window.showOpenFilePicker(Object.assign({ multiple: false }, GROUND_DATA_FILE_PICKER_OPTIONS));
    const file = await handle.getFile();
    const text = await file.text();
    groundData = cloneData(parseGroundDataFile(text));
    activeFileHandle = handle;
    switchAirport(Object.keys(groundData.airports || {}).sort()[0] || "EPKK");
    setStatus("Opened " + file.name + ". Future saves will write to this selected file.", "ok");
  } catch (error) {
    if (error && error.name === "AbortError") {
      setStatus("Open file cancelled.", "warn");
      return;
    }
    setStatus("Could not open ground-data.js: " + getErrorMessage(error), "warn");
  }
}

async function saveGroundDataFile() {
  const text = generateFileText();
  try {
    let fileHandle = activeFileHandle;
    if (!fileHandle) {
      if (!window.showSaveFilePicker) {
        downloadGroundDataFile(text, {
          message: "Browser cannot overwrite local files here. Downloaded generated ground-data.js instead.",
          tone: "warn"
        });
        return;
      }
      fileHandle = await window.showSaveFilePicker(Object.assign({ suggestedName: "ground-data.js" }, GROUND_DATA_FILE_PICKER_OPTIONS));
    }

    const canWrite = await requestFileHandlePermission(fileHandle, "readwrite");
    if (!canWrite) {
      throw new Error("write permission was not granted");
    }

    const writable = await fileHandle.createWritable();
    await writable.write(text);
    await writable.close();
    activeFileHandle = fileHandle;
    setStatus("Saved " + (fileHandle.name || "ground-data.js") + ".", "ok");
    render();
  } catch (error) {
    if (error && error.name === "AbortError") {
      setStatus("Save cancelled.", "warn");
      return;
    }
    downloadGroundDataFile(text, {
      message: "Could not write selected file (" + getErrorMessage(error) + "). Downloaded generated ground-data.js instead.",
      tone: "warn"
    });
  }
}

function downloadGroundDataFile(text = generateFileText(), options = {}) {
  const blob = new Blob([text], { type: "text/javascript" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = "ground-data.js";
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
  setStatus(options.message || "Downloaded generated ground-data.js.", options.tone || "ok");
}

