function mergeStandStartOptionsIntoConnections(airportData) {
  if (!airportData || !airportData.connections) {
    return;
  }

  forEachApronStand(airportData, (stand) => {
    const standId = normalizeThingId(stand && stand.id);
    if (!standId) {
      return;
    }

    ensureThing(airportData, standId, "stand", clean(stand.label) || "Stand " + standId);
    const startOptions = Array.isArray(stand.startOptions) ? stand.startOptions : [];
    const legalStartOptions = startOptions
      .map(normalizeThingId)
      .filter(Boolean)
      .filter((targetId) => {
        const inferredTargetType = inferThingType(targetId);
        ensureThing(
          airportData,
          targetId,
          inferredTargetType,
          inferredTargetType === "taxiway" ? "Taxiway " + targetId : targetId
        );
        return canConnectThingIds(airportData, standId, targetId);
      });

    airportData.connections[standId] = sortConnectionIds(
      (airportData.connections[standId] || []).concat(legalStartOptions)
    );
  });
}

function syncStandStartOptions(airportData) {
  if (!airportData || !airportData.connections) {
    return;
  }

  forEachApronStand(airportData, (stand) => {
    const standId = normalizeThingId(stand && stand.id);
    if (!standId) {
      return;
    }
    stand.startOptions = sortConnectionIds(airportData.connections[standId])
      .filter((targetId) => {
        const target = getThingById(airportData, targetId);
        return target && target.type === "taxiway";
      });
  });
}

function ensureBidirectionalConnections(airportData) {
  if (!airportData || !airportData.connections) {
    return;
  }

  Object.keys(airportData.connections).forEach((fromId) => {
    const normalizedFromId = normalizeThingId(fromId);
    if (!normalizedFromId) {
      return;
    }

    if (normalizedFromId !== fromId) {
      airportData.connections[normalizedFromId] = sortConnectionIds(
        (airportData.connections[normalizedFromId] || []).concat(airportData.connections[fromId] || [])
      );
      delete airportData.connections[fromId];
    }

    airportData.connections[normalizedFromId] = sortConnectionIds(airportData.connections[normalizedFromId])
      .filter((targetId) => canConnectThingIds(airportData, normalizedFromId, targetId));
    airportData.connections[normalizedFromId].forEach((targetId) => {
      airportData.connections[targetId] = sortConnectionIds(
        (airportData.connections[targetId] || []).concat(normalizedFromId)
      ).filter((returnTargetId) => canConnectThingIds(airportData, targetId, returnTargetId));
    });
  });
}

function ensureHoldingPointRunwayEndpoints(airportData) {
  if (!airportData || !Array.isArray(airportData.elements) || !airportData.connections) {
    return;
  }

  airportData.elements.slice().forEach((thing) => {
    const runwayEndpointId = thing && thing.type === "holdingPoint"
      ? getRunwayEndpointFromHoldingPoint(thing.id)
      : "";
    if (!runwayEndpointId) {
      return;
    }

    if (!airportData.elements.some((entry) => entry.id === runwayEndpointId)) {
      airportData.elements.push({
        id: runwayEndpointId,
        type: "runway",
        label: "RWY " + runwayEndpointId.slice(2)
      });
    }
    airportData.connections[thing.id] = sortConnectionIds((airportData.connections[thing.id] || []).concat(runwayEndpointId));
    airportData.connections[runwayEndpointId] = sortConnectionIds((airportData.connections[runwayEndpointId] || []).concat(thing.id));
  });
}

